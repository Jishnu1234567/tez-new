// One-off helper: downloads the Google Fonts the site uses (Latin and Latin-extended
// subsets only) into public/fonts/ and writes src/fonts.generated.js with their
// @font-face rules. Self-hosting removes a render-blocking request to another server.
// Run again only if a font family changes:  node scripts/fetch-fonts.mjs
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(root, 'public/fonts');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

export const FAMILIES = {
  interTight: 'Inter+Tight:wght@200..700',
  instrumentSerif: 'Instrument+Serif:ital@0;1',
  archivo: 'Archivo:wdth,wght@62..125,700..900',
  googleSansFlex: 'Google+Sans+Flex:wght@100..900',
  instrumentSans: 'Instrument+Sans:wdth,wght@75..100,400..700',
  outfit: 'Outfit:wght@300..700',
  inter: 'Inter:wght@400..600',
  anton: 'Anton',
  robotoCondensed: 'Roboto+Condensed:wght@400..700',
  bigShoulders: 'Big+Shoulders+Display:wght@700..900',
};
const KEEP = new Set(['latin', 'latin-ext']);

await mkdir(outDir, { recursive: true });
const result = {};
const preload = {};
for (const [key, spec] of Object.entries(FAMILIES)) {
  const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${spec}&display=swap`, { headers: { 'User-Agent': UA } })).text();
  const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g)];
  let out = '';
  for (const [, subset, block] of blocks) {
    if (!KEEP.has(subset)) continue;
    const url = /url\((https:[^)]+)\)/.exec(block)[1];
    const buf = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
    const name = `${key}-${subset}-${createHash('sha1').update(buf).digest('hex').slice(0, 8)}.woff2`;
    await writeFile(resolve(outDir, name), buf);
    out += block.replace(url, `/fonts/${name}`).replace(/\s+/g, ' ') + '\n';
    if (subset === 'latin' && !preload[key]) preload[key] = `/fonts/${name}`;
    console.log(`  ${name}  ${(buf.length / 1024).toFixed(0)} kB`);
  }
  result[key] = out.trim();
}
await writeFile(resolve(root, 'src/fonts.generated.js'),
  `// Generated by scripts/fetch-fonts.mjs. Do not edit by hand.\nexport const FONT_FACES = ${JSON.stringify(result, null, 2)};\nexport const FONT_PRELOAD = ${JSON.stringify(preload, null, 2)};\n`);
console.log('wrote src/fonts.generated.js');
